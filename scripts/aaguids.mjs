/**
 * @fileoverview Regenerate src/aaguids.js, the authenticator model names
 * shown for AAGUIDs, from the community list (names only, no icons).
 *
 * Usage: node scripts/aaguids.mjs [combined_aaguid.json]
 * Without a file, downloads it.
 */

import fs from 'node:fs';
import path from 'node:path';

const REPO =
    'https://github.com/passkeydeveloper/passkey-authenticator-aaguids';
const SOURCE = 'https://raw.githubusercontent.com/passkeydeveloper/' +
    'passkey-authenticator-aaguids/main/combined_aaguid.json';

/** Seen on real devices but missing from the list. */
const EXTRA = {
  '84039877-a54b-dfbb-04a8-2df2fa2a116e': {name: 'ChromeOS (built-in)'},
};

const list = process.argv[2] ?
    JSON.parse(fs.readFileSync(process.argv[2], 'utf8')) :
    await (await fetch(SOURCE)).json();

const names = Object.entries({...EXTRA, ...list})
    .filter(([aaguid, {name}]) =>
      /^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$/.test(aaguid) &&
      typeof name === 'string')
    .map(([aaguid, {name}]) => [aaguid, name.trim()])
    .sort(([a], [b]) => a.localeCompare(b));
if (names.length === 0) {
  throw new Error('the list is empty: it may have been retired');
}

const out = path.join(path.dirname(new URL(import.meta.url).pathname),
                      '../src/aaguids.js');
fs.writeFileSync(out, `// SPDX-License-Identifier: BSD-3-Clause

/**
 * @fileoverview Authenticator model names by AAGUID, from the community list
 * at ${REPO}.
 * Generated by scripts/aaguids.mjs: don't edit.
 */

/** @type {!Map<string, string>} */
export const AAGUID_NAMES = new Map([
${names.map(([aaguid, name]) =>
    `  [${JSON.stringify(aaguid)}, ${JSON.stringify(name)}],`).join('\n')}
]);
`);
console.log(`wrote ${names.length} names to ${out}`);
